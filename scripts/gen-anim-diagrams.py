"""Write the animated feature diagrams in docs/ux/anim.

Each diagram is one SMIL timeline: every element shows, moves or fades at a
fraction (0..1) of the scene's loop. The scene fades out and back in at the
loop boundary so the jump back to the start is not visible.

    python3 scripts/gen-anim-diagrams.py
"""

